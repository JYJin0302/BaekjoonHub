ll gcd(ll a, ll b) {
    if (a > b) swap(a, b);
    if (a == 0) return b;
    return gcd(b % a, a);
}

ll fastPow(ll b, ll ex, ll mod) {
    ll res = 1;
    while (ex) {
        if (ex & 1) res = res * b % mod;
        ex >>= 1;
        b = b * b % mod;
    }
    return res;
}


void solve() {

    ll x, y, c;
    cin >> x >> y >> c;

    ll d = x * x + y * y;
    ll sd = sqrt(d);

    if (sd*sd == d && d % c == 0) {
        cout << sd / c << '\n';
        return;
    }

    if (d < c * c) cout << 2 << '\n';
    else cout << sd / c + 1 << '\n';
}

