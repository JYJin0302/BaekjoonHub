int In[1010101];
int Out[1010101];
void solve() {
    int n, m;
    cin >> n >> m;

    for (int i = 0; i < m; i++) {
        int a, b;
        cin >> a >> b;
        
        Out[a]++;
        In[b]++;
    }

    int ans = m;
    for (int i = 1; i <= n; i++) {
        ans -= min(In[i], Out[i]);
    }
    cout << ans;

}

